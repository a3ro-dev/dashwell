// Compiles real ad-block lists into static files the extension ships with.
// adblock-rs is a native Node module, so it runs here at build time, not in the browser.
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const { FilterSet, Engine } = createRequire(import.meta.url)('adblock-rs');

const LISTS = {
  'easylist.txt': 'https://easylist.to/easylist/easylist.txt',
  'adguard-base.txt': 'https://filters.adtidy.org/extension/ublock/filters/2.txt',
};
const PAGE = 'https://www.tumblr.com/dashboard';
const OUT = new URL('../extension/', import.meta.url);
const CACHE = new URL('../.cache/', import.meta.url);

async function load(name, url) {
  const file = new URL(name, CACHE);
  if (!process.argv.includes('--refresh')) {
    try { return await readFile(file, 'utf8'); } catch {}
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const text = await res.text();
  await mkdir(CACHE, { recursive: true });
  await writeFile(file, text);
  return text;
}

const texts = await Promise.all(Object.entries(LISTS).map(([n, u]) => load(n, u)));
const filterSet = new FilterSet(true);
for (const t of texts) filterSet.addFilters(t);
const engine = new Engine(filterSet);

// Cosmetic: let adblock-rs resolve tumblr-specific hide rules (and their exceptions).
const cosmetic = engine.urlCosmeticResources(PAGE);
// uBlock-only procedural syntax (:contains, :upward, ...) isn't CSS; a browser would drop it anyway.
const selectors = [...cosmetic.hide_selectors].filter((s) => !/:(contains|has-text|upward|xpath|matches-css|-abp-)/.test(s));
// One rule per selector: a single unsupported selector in a list would void the whole rule.
const css =
  `/* generated by scripts/build-filters.mjs from ${Object.keys(LISTS).join(', ')} */\n` +
  selectors.map((s) => `${s} { display: none !important; }`).join('\n') + '\n';

// Network: plain "||domain^" rules collapse into one DNR rule via requestDomains.
// engine.check drops anything an @@ exception allows when loaded from tumblr.
const domains = new Set();
for (const t of texts) {
  for (const m of t.matchAll(/^\|\|([a-z0-9.-]+)\^(?:\$third-party)?\r?$/gm)) domains.add(m[1]);
}
const blocked = [...domains].filter(
  (d) => !d.endsWith('tumblr.com') && engine.check(`https://${d}/ad.js`, PAGE, 'script', ''),
);
// Path rules aimed at tumblr itself, kept as-is (DNR urlFilter uses the same || ^ * syntax).
const tumblrPaths = texts
  .flatMap((t) => t.split('\n'))
  .map((l) => l.trim())
  .filter((l) => /^\|\|[a-z0-9.-]*tumblr\.com\/[^$]*$/.test(l));

const resourceTypes = ['script', 'sub_frame', 'image', 'xmlhttprequest', 'media', 'ping', 'other'];
const rules = [
  {
    id: 1,
    priority: 1,
    action: { type: 'block' },
    condition: { requestDomains: blocked, initiatorDomains: ['tumblr.com'], resourceTypes },
  },
  ...tumblrPaths.map((urlFilter, i) => ({
    id: i + 2,
    priority: 1,
    action: { type: 'block' },
    condition: { urlFilter, resourceTypes },
  })),
];

await mkdir(new URL('rules/', OUT), { recursive: true });
await writeFile(new URL('rules/ads.json', OUT), JSON.stringify(rules));
await writeFile(new URL('cosmetic.css', OUT), css);
console.log(
  `cosmetic selectors: ${selectors.length} (procedural skipped: ${cosmetic.procedural_actions?.length ?? 0})\n` +
    `blocked ad domains: ${blocked.length} of ${domains.size}\ntumblr path rules: ${tumblrPaths.join(', ')}`,
);
